import builtins
from pathlib import Path
from typing import Protocol

from ocint.daemon.models import GitRepository, PromptObservation, PublicationRequest, PublicationResult, Worktree
from ocint.daemon.pull_request_job.models import (
    Checkpoint,
    PullRequestJob,
    PullRequestJobRequest,
    SourcePullRequestJobRequest,
)


class PullRequestJobStore(Protocol):
    def submit(self, request: PullRequestJobRequest) -> PullRequestJob: ...
    def retry(self, previous: PullRequestJob, request: PullRequestJobRequest) -> PullRequestJob: ...
    def claim(self, job_id: str) -> PullRequestJob | None: ...
    def pending_ids(self) -> builtins.list[str]: ...
    def get(self, job_id: str) -> PullRequestJob: ...
    def list(self, limit: int = 100) -> builtins.list[PullRequestJob]: ...
    def checkpoint(self, job_id: str, checkpoint: Checkpoint) -> PullRequestJob: ...
    def complete(self, job_id: str) -> PullRequestJob: ...
    def fail(self, job_id: str, error: str) -> PullRequestJob: ...
    def requeue(self, job_id: str) -> None: ...
    def reconcile(self) -> int: ...
    def owned_pull_request(self, source_thread_id: str, repository: str) -> tuple[int, str] | None: ...
    def set_owned_pull_request(self, source_thread_id: str, repository: str, number: int, url: str) -> None: ...


class OpenCodeGateway(Protocol):
    server_url: str

    async def create(self, directory: Path, identity: str) -> str: ...
    async def observe_prompt(self, directory: Path, session_id: str, text: str) -> PromptObservation: ...
    async def prompt(self, directory: Path, session_id: str, text: str) -> None: ...
    async def wait_for_completion(self, directory: Path, session_id: str, text: str) -> None: ...


class GitGateway(Protocol):
    async def provision(self, repository: GitRepository, job_id: str) -> Worktree: ...
    async def validate(self, worktree: Worktree, checks: tuple[tuple[str, ...], ...]) -> None: ...
    async def commit(self, worktree: Worktree, message: str, author_name: str, author_email: str) -> str: ...
    async def push(self, worktree: Worktree) -> None: ...


class PullRequestPublisher(Protocol):
    async def publish(self, request: PublicationRequest) -> PublicationResult: ...


class PullRequestJobRunnerGateway(Protocol):
    activity_generation: int

    @property
    def is_idle(self) -> bool: ...

    def recover(self) -> list[str]: ...
    def schedule_pending(self, job_ids: list[str]) -> None: ...
    def submit(self, request: PullRequestJobRequest) -> PullRequestJob: ...
    def accept(self, request: PullRequestJobRequest) -> PullRequestJob: ...
    def submit_source(self, request: SourcePullRequestJobRequest) -> PullRequestJob: ...
    def accept_source(self, request: SourcePullRequestJobRequest) -> PullRequestJob: ...
    def retry(self, previous: PullRequestJob, request: PullRequestJobRequest) -> PullRequestJob: ...
    def accept_retry(self, previous: PullRequestJob, request: PullRequestJobRequest) -> PullRequestJob: ...
    def retry_source(self, previous: PullRequestJob, request: SourcePullRequestJobRequest) -> PullRequestJob: ...
    def accept_source_retry(self, previous: PullRequestJob, request: SourcePullRequestJobRequest) -> PullRequestJob: ...
    def schedule_accepted(self, job_id: str) -> None: ...
    def get(self, job_id: str) -> PullRequestJob: ...
    def reusable(self, candidate_ids: tuple[str, ...]) -> PullRequestJob | None: ...
    def abandon(self, job_id: str, reason: str) -> None: ...
    async def wait_until_idle(self) -> None: ...
    async def wait_for_completion(self) -> None: ...
    async def close(self) -> None: ...
