import asyncio
from collections.abc import Callable
from contextlib import AbstractContextManager
from typing import Protocol

from ocint.daemon.coordinator.models import (
    ActorKind,
    Conversation,
    ConversationIdentity,
    ConversationMessage,
    Delivery,
    DeliveryLookup,
    DeliveryReceipt,
    DeliveryRequest,
    IngestResult,
    MessageKind,
    OpenCodeCompletion,
    OpenCodePromptObservation,
    OpenCodePromptRequest,
    OpenCodeSessionId,
    OpenCodeSessionRequest,
    PreparedMessage,
    ResponseChunk,
    Turn,
)


class OpenCodeCoordinator(Protocol):
    async def create_or_reuse_session(self, request: OpenCodeSessionRequest) -> OpenCodeSessionId: ...
    async def observe_prompt(self, request: OpenCodePromptRequest) -> OpenCodePromptObservation: ...
    async def submit_prompt(self, request: OpenCodePromptRequest) -> None: ...
    async def wait_for_completion(self, request: OpenCodePromptRequest) -> OpenCodeCompletion: ...


class CoordinatorDelivery(Protocol):
    async def find_delivery(self, request: DeliveryRequest) -> DeliveryLookup: ...
    async def post(self, request: DeliveryRequest) -> DeliveryReceipt: ...


class CoordinatorPersistence(Protocol):
    def ingest(self, prepared: PreparedMessage) -> IngestResult: ...
    def expire_orphans(self, created_before: str) -> int: ...
    def claim_turn(self, ready_at: str) -> Turn | None: ...
    def conversation(self, conversation_id: int) -> Conversation: ...
    def turn(self, turn_id: int) -> Turn: ...
    def set_session(self, conversation_id: int, session_id: str) -> Conversation: ...
    def mark_prompt_intended(self, turn_id: int) -> Turn: ...
    def mark_prompt_submitted(self, turn_id: int) -> Turn: ...
    def store_response(self, turn_id: int, assistant_message_id: str, response_text: str) -> Turn: ...
    def store_failure_response(self, turn_id: int, error: str, safe_response: str) -> Turn: ...
    def schedule_retry(self, turn_id: int, retry_not_before: str, error: str) -> Turn: ...
    def create_deliveries(self, turn_id: int, chunks: tuple[ResponseChunk, ...]) -> tuple[Delivery, ...]: ...
    def deliveries(self, turn_id: int) -> tuple[Delivery, ...]: ...
    def next_delivery(self, turn_id: int, ready_at: str) -> Delivery | None: ...
    def mark_delivery_intended(self, turn_id: int, chunk_index: int) -> Delivery: ...
    def mark_delivered(self, turn_id: int, chunk_index: int, provider_message_id: str) -> Delivery: ...
    def schedule_delivery_retry(self, turn_id: int, chunk_index: int, retry_not_before: str) -> Delivery: ...
    def complete_turn(self, turn_id: int) -> Turn: ...


class CoordinatorOperations(Protocol):
    safe_failure_text: str

    def prepare(self, message: ConversationMessage, kind: MessageKind, actor_kind: ActorKind) -> PreparedMessage: ...
    def session_identity(self, identity: ConversationIdentity) -> str: ...
    def chunks(self, response: str) -> tuple[ResponseChunk, ...]: ...


class CoordinatorWorker(Protocol):
    def wake(self) -> None: ...
    async def run_once(self) -> bool: ...
    async def run(self, stop: asyncio.Event) -> None: ...


class CoordinatorProcess(Protocol):
    async def start(self) -> None: ...
    async def close(self) -> None: ...
    async def wait_exited(self) -> int: ...


class CoordinatorIngress(Protocol):
    async def __call__(self, shutdown: asyncio.Event, /) -> None: ...


class ShutdownSignalRegistrar(Protocol):
    def register(self, request_shutdown: Callable[[], None]) -> AbstractContextManager[None]: ...


class RetryableCoordinatorError(Exception):
    def __init__(self, message: str, retry_after_seconds: float | None = None) -> None:
        super().__init__(message)
        if retry_after_seconds is not None and retry_after_seconds <= 0:
            raise ValueError("retry delay must be positive")
        self.retry_after_seconds = retry_after_seconds


class RetryableCoordinatorDeliveryError(RetryableCoordinatorError):
    """A temporary delivery failure whose response remains valid."""


class TerminalCoordinatorError(Exception):
    """A classified adapter failure that should not be retried."""


class TerminalCoordinatorDeliveryError(Exception):
    """A delivery failure that must stop the worker without changing its response."""
